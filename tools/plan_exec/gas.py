"""عمليات Apps Script للخطة (§3.3، §3.7): التجهيز، الـ push، القراءة الراجعة، النسخ، النشر، إعادة التوجيه، والتصريف.

كل أمر clasp بيتنادى بـ -P apps_script/.clasp.json صريح (مش فولدر العمل الحالي). الإنشاء idempotent: النسخة والنشر
بيتعرفوا بالوصف (cf-v2-<run> / cf-rehearsal-<run>)، فلو الأمر اتنفّذ ورده ضاع، الإعادة بتلاقي الموجود ومابتكررش.
"""
from __future__ import annotations

import hashlib
import json
import re
import shutil
import subprocess
import time
from pathlib import Path

from . import ROOT, SECRETS

APPS = ROOT / "apps_script"
SRC = APPS / "src"
STAGING = APPS / "push"
PROJECT = APPS / ".clasp.json"
ALLOWLIST = ("facebook_sheet_receiver.gs", "sheet_setup.gs", "appsscript.json")
GENERATED = "zz_config.gs"
CONFIG_VERSION = 1


class GasError(Exception):
    pass


def sha256(data: bytes | str) -> str:
    return hashlib.sha256(data.encode("utf-8") if isinstance(data, str) else data).hexdigest()


def key_hash(name: str, secrets: Path = SECRETS) -> str:
    return sha256((secrets / f"{name}.key").read_text(encoding="utf-8").strip())


def write_project_file(script_id: str, project: Path = PROJECT) -> Path:
    project.write_text(json.dumps({"scriptId": script_id, "rootDir": "push"}, indent=2), encoding="utf-8")
    return project


def config_source(production_id: str, admin_hash: str, ingest_hash: str, post_replies: bool = False) -> str:
    """zz_config.gs: الهاشات بس (عمر المفتاح نفسه ما بيتكتب هنا)، والملف برّه git."""
    for h in (admin_hash, ingest_hash):
        if not re.fullmatch(r"[0-9a-f]{64}", h):
            raise GasError("key hash must be 64 hex chars")
    cfg = {"PRODUCTION_ID": production_id, "ADMIN_HASH": admin_hash, "INGEST_HASH": ingest_hash,
           "CONFIG_VERSION": CONFIG_VERSION, "POST_REPLIES": bool(post_replies)}
    return "// generated by tools/plan_exec/gas.py — not in git\nconst CF_CONFIG = " + json.dumps(cfg, indent=2) + ";\n"


def build_staging(production_id: str, admin_hash: str, ingest_hash: str, src: Path = SRC, staging: Path = STAGING) -> dict:
    """فولدر push جديد كل مرة: الملفات المسموح بيها + الإعداد المتولّد، ولا حاجة تانية. بيرجّع {file: sha256}."""
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)
    hashes = {}
    for name in ALLOWLIST:
        data = (src / name).read_bytes()
        (staging / name).write_bytes(data)
        hashes[name] = sha256(data)
    gen = config_source(production_id, admin_hash, ingest_hash)
    (staging / GENERATED).write_text(gen, encoding="utf-8")
    hashes[GENERATED] = sha256(gen)
    extra = sorted(p.name for p in staging.iterdir() if p.name not in hashes)
    if extra:
        raise GasError(f"unexpected files in staging: {extra}")
    return hashes


def normalized(name: str, data: bytes) -> str:
    """مقارنة القراءة الراجعة: الـ JSON بالمعنى، والكود من غير فرق نهايات السطور."""
    text = data.decode("utf-8")
    if name.endswith(".json"):
        return json.dumps(json.loads(text), sort_keys=True)
    return "\n".join(line.rstrip("\r") for line in text.split("\n")).rstrip("\n")


def readback_matches(clone_dir: Path, staging: Path = STAGING) -> tuple[bool, list[str]]:
    """الملفات اللي اتسحبت من الـ remote (clasp بيكتب .gs كـ .js) = الـ staging بالظبط، ولا ناقص ولا زيادة."""
    local = {p.stem: (p.name, p.read_bytes()) for p in staging.iterdir() if p.is_file()}
    remote = {p.stem: (p.name, p.read_bytes()) for p in clone_dir.iterdir() if p.is_file() and p.name != ".clasp.json"}
    problems = []
    for stem in sorted(set(local) | set(remote)):
        if stem not in remote:
            problems.append(f"missing remotely: {stem}")
        elif stem not in local:
            problems.append(f"unexpected remote file: {stem}")
        elif normalized(local[stem][0], local[stem][1]) != normalized(remote[stem][0], remote[stem][1]):
            problems.append(f"content differs: {stem}")
    return not problems, problems


DEPLOY_LINE = re.compile(r"^-\s+(\S+)\s+@(HEAD|\d+)(?:\s+-\s+(.*))?$")
VERSION_LINE = re.compile(r"^(\d+)\s+-\s+(.*)$")


class Clasp:
    """غلاف clasp. runner قابل للاستبدال في الاختبارات؛ في الحقيقي subprocess.run."""

    def __init__(self, project: Path = PROJECT, runner=None, exe: str = "clasp"):
        self.project = project
        self.runner = runner or self._subprocess
        self.exe = exe

    def _subprocess(self, args: list[str], cwd: Path | None = None) -> str:
        proc = subprocess.run([shutil.which(self.exe) or self.exe, *args], capture_output=True, text=True,
                              encoding="utf-8", errors="replace", timeout=300, cwd=str(cwd or ROOT))
        if proc.returncode != 0:
            raise GasError(f"clasp {args[0]} failed: {(proc.stderr or proc.stdout)[-400:]}")
        return proc.stdout

    def run(self, *args: str, project: bool = True) -> str:
        return self.runner((["-P", str(self.project)] if project else []) + list(args))

    def push(self) -> str:
        return self.run("push", "--force")

    def list_versions(self) -> list[tuple[int, str]]:
        out = []
        for line in self.run("list-versions").splitlines():
            m = VERSION_LINE.match(line.strip())
            if m:
                out.append((int(m.group(1)), m.group(2).strip()))
        return out

    def create_version(self, description: str) -> int:
        out = self.run("create-version", description)
        m = re.search(r"version (\d+)", out)
        if not m:
            raise GasError(f"no version number in: {out[-200:]}")
        return int(m.group(1))

    def list_deployments(self, script_id: str) -> list[dict]:
        rows = []
        for line in self.run("list-deployments", script_id, project=False).splitlines():
            m = DEPLOY_LINE.match(line.strip())
            if m:
                rows.append({"id": m.group(1), "version": m.group(2), "description": (m.group(3) or "").strip()})
        return rows

    def create_deployment(self, version: int, description: str) -> str:
        out = self.run("create-deployment", "-V", str(version), "-d", description)
        m = re.search(r"(AKfy\S+)", out)
        if not m:
            raise GasError(f"no deployment id in: {out[-200:]}")
        return m.group(1).rstrip(".")

    def update_deployment(self, deployment_id: str, version: int, description: str) -> str:
        return self.run("update-deployment", deployment_id, "-V", str(version), "-d", description)

    def delete_deployment(self, deployment_id: str) -> str:
        return self.run("delete-deployment", deployment_id)

    def clone(self, script_id: str, dest: Path, version: int | None = None) -> Path:
        if dest.exists():
            shutil.rmtree(dest)
        dest.mkdir(parents=True)
        args = ["clone-script", script_id] + ([str(version)] if version else [])
        # clone بيكتب .clasp.json في فولدر العمل: يشتغل من جوه dest، عشان مايسيبش ملف في جذر المشروع
        if self.runner == self._subprocess:
            self._subprocess(args, cwd=dest)
        else:
            self.runner(args + ["--rootDir", str(dest)])
        return dest


def ensure_version(clasp: Clasp, description: str) -> int:
    for number, desc in clasp.list_versions():
        if desc == description:
            return number
    return clasp.create_version(description)


def ensure_deployment(clasp: Clasp, script_id: str, version: int, description: str) -> str:
    for row in clasp.list_deployments(script_id):
        if row["description"] == description:
            if row["version"] != str(version):
                clasp.update_deployment(row["id"], version, description)
            return row["id"]
    return clasp.create_deployment(version, description)


def repoint_all(clasp: Clasp, script_id: str, version: int, order: list[str], keep_ids: set[str], log=None) -> list[dict]:
    """كل نشر بنسخة (مش HEAD، ومش اللي في keep_ids) يتوجّه للنسخة version، بالترتيب المطلوب الأول.
    قابل للاستكمال: اللي على version خلاص بيتعدّى. بيرجّع نتيجة كل واحد (من غير ما يطبع الـ ids)."""
    rows = [r for r in clasp.list_deployments(script_id) if r["version"] != "HEAD" and r["id"] not in keep_ids]
    rank = {d: i for i, d in enumerate(order)}
    rows.sort(key=lambda r: (rank.get(r["id"], len(rank)), r["id"]))
    results = []
    for row in rows:
        before = row["version"]
        if before != str(version):
            clasp.update_deployment(row["id"], version, row["description"] or "cf-v2")
        results.append({"id": row["id"], "from": before, "to": str(version)})
        if log:
            log(results[-1])
    return results


def exposed_v1(clasp: Clasp, script_id: str, first_v2_version: int, keep_ids: set[str] = frozenset()) -> list[dict]:
    """أي نشر بنسخة أقدم من أول نسخة v2 = لسه بيشغّل كود v1 على رابط عام."""
    return [r for r in clasp.list_deployments(script_id)
            if r["version"] != "HEAD" and r["id"] not in keep_ids and int(r["version"]) < first_v2_version]


def drain(fingerprint, sleep=time.sleep, settle_s: int = 420, recheck_s: int = 60, cycles: int = 3) -> bool:
    """بعد آخر إعادة توجيه: نستنى settle_s (أكتر من حد التنفيذ 6 دقايق)، وبعدين البصمة لازم تفضل ثابتة مرتين
    بينهم recheck_s. لو اتغيرت، دورة كمان (cycles بالكتير)."""
    for _ in range(cycles):
        sleep(settle_s)
        first = fingerprint()
        sleep(recheck_s)
        if fingerprint() == first:
            return True
    return False
